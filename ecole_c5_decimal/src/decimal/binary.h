unsigned my_dec_getbit(my_decimal num, short di);  // di == 68;

/**
 * @brief Извлекает n-битное поле из значения типа my_decimal, начиная с
 * указанной позиции
 *
 * @param num Исходное значение типа my_decimal для извлечения битов
 * @param start_pos Начальная позиция
 * @param n Количество извлекаемых битов (отсчет от младшего бита к старшему)
 * @return my_decimal Извлеченные n битов, сдвинутые к правому краю
 *
 * @note Операции выполняются только над MANTISSA значения my_decimal num
 * @note Если n превышает доступное количество битов в MANTISSA, возвращает
 * только доступные биты
 * @example my_dec_getbits(0b11001011, 2, 3) возвращает (0b...010.. >> 2) ==
 * 0b010 (биты 2,3,4 сдвинутые к правому краю)
 */
my_decimal my_dec_getbits(my_decimal num, int start_pos, int n, int *status);

/**
 * @brief Реализует полный сумматор с помощью логических вентилей для типа
 * my_decimal (МАНТИССА).
 *
 * Эта функция вычисляет сумму двух неотрицательных целых битов,
 * `b1` и `b2`, вместе с входным переносом, на который ссылается `cin`.
 * Она возвращает результирующую сумму и обновляет выходной перенос.
 *
 * Полный сумматор работает следующим образом:
 * - Вычисляет бит суммы, который является результатом сложения
 *   соответствующих битов `b1`, `b2` и `cin`.
 * - Определяет бит переноса, который возникает, если происходит
 *   переполнение при сложении битов.
 *
 * @param a1   Первое слагаемое (бит).
 * @param a2   Второе слагаемое (бит)
 * @param cin  Указатель на входной перенос (1 бит).
 * @return my_decimal	Результирующая сумма.
 */
my_decimal my_dec_full_adder(my_decimal b1, my_decimal b2,
                               my_decimal *cin);

/**
 * @brief Выполняет побитовую операцию & (И) между двумя десятичными числами
 * (только для битов мантиссы)
 *
 * @return my_decimal Результат n1 & n2 (побитовое И)
 *
 * @note Применяет операцию И только к числовым частям (limbs 0 до LIMB_MAX-2)
 * @note Часть с метаданными (LIMB_MAX-1) сохраняется из n1
 */
my_decimal my_dec_and(my_decimal n1, my_decimal n2);

/**
 * @brief Выполняет побитовую операцию | (ИЛИ) между двумя десятичными числами
 * (только для битов мантиссы)
 *
 * @param n1 Первый десятичный операнд
 * @param n2 Второй десятичный операнд
 * @return my_decimal Результат n1 | n2 (побитовое ИЛИ)
 *
 * @note Применяет операцию ИЛИ только к числовым частям (limbs 0 до LIMB_MAX-2)
 * @note Часть с метаданными (LIMB_MAX-1) сохраняется из n1
 */
my_decimal my_dec_or(my_decimal n1, my_decimal n2);

/**
 * @brief Выполняет побитовую операцию ^ (исключающий ИЛИ) между двумя
 * десятичными числами (только для битов мантиссы)
 *
 * @param n1 Первый десятичный операнд
 * @param n2 Второй десятичный операнд
 * @return my_decimal Результат n1 ^ n2 (побитовое исключающее ИЛИ)
 *
 * @note Применяет операцию XOR только к числовым частям (limbs 0 до LIMB_MAX-2)
 * @note Часть с метаданными (LIMB_MAX-1) сохраняется из n1
 */
my_decimal my_dec_xor(my_decimal n1, my_decimal n2);

/**
 * @brief Выполняет побитовую операцию ~ (NOT - инверсия) над десятичным числом
 * (только для битов мантиссы)
 *
 * @param src Исходное десятичное число для инверсии
 * @return my_decimal Результат ~src (побитовое НЕ)
 *
 * @note Инвертирует только числовые части (limbs 0 до LIMB_MAX-2)
 * @note Часть с метаданными (LIMB_MAX-1) остается без изменений
 */
my_decimal my_dec_invert(my_decimal src);

/**
 * @brief Выполняет операцию поразрядного битового сдвига десятичного числа
 * (только для битов мантиссы, не трогает bits[METADATA])
 * @param num Число my_decimal для сдвига
 * @param n_shift На сколько разрядов нужно сдвинуть. (—)n_shift == сдвиг влево
 * == <<
 * @param *status Указатель на статус ошибки
 * @return [my_decimal num >>/<< n_shift]
 * @note Если модуль n_shift не в диапазоне (от 1 до MANTISSA_W), функция вернет
 * изначальный my_decimal num, а *status станет ERROR, чтобы избежать UB
 */
my_decimal my_dec_shift(my_decimal num, int n_shift, int *status);

/**
 * @brief Выполняет циклический сдвиг (вращение) десятичного числа (только для
 * битов мантиссы, с сохранением метаданных)
 * @param num Число my_decimal
 * @param n_shift Количество битов для сдвига (положительное == вправо,
 * отрицательное == влево)
 * @param *status Указатель на статус ошибки
 * @return my_decimal Результат вращения на n_shift битов
 *
 * @note Вращает только числовые части, сохраняя метаданные
 * @note "Вращение" означает, что биты, вытесненные справа, вставляются слева
 */
my_decimal my_dec_rotate(my_decimal num, int n_shift, int *status);
